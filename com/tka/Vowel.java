package com.tka;

public class Vowel {
	public static void main(String[] args) {
		char vowel = 'a';

		if (vowel == 'a' || vowel == 'e' || vowel == 'i' || vowel == 'o' || vowel == 'u') {
			System.out.println(vowel + " is a Vowel");
		} else {
			System.out.println(vowel + " is a Consonant");
		}

	}

}
